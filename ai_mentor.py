import os
from typing import Dict, Any, Optional
from google import genai
from config import GEMINI_API_KEY

MODELS_TO_TRY = [
    "gemini-3.5-flash-lite",
    "gemini-3.5-flash"
]

class AIMentor:
    def __init__(self, api_key: str = GEMINI_API_KEY):
        self.client = genai.Client(api_key=api_key)

    def process_article(self, article: Dict[str, Any]) -> Optional[str]:
        title = article["title"]
        summary = article["summary"]
        source = article["source"]
        category = article["category"]
        link = article["link"]

        prompt = f"""
Ты — персональный наставник и IT-ментор для студента технического вуза.
Твоя цель — отбирать ПРАКТИЧЕСКИЕ, ЗАХВАТЫВАЮЩИЕ И ВАЖНЫЕ материалы из мира IT:
1. 🔥 Главные события IT-индустрии и релизы: исторические сделки и IPO (Anthropic, OpenAI), новые возможности ОС (Android, iOS, Linux), важные решения регуляторов, сбои и блокировки.
2. 🤖 ИИ: модели, критика и практика: сравнения нейросетей, критический разбор («что не так с новой моделью X»), бенчмарки, протокол MCP, локальные LLM (Ollama, vLLM, квантование), RAG и агентные фреймворки.
3. 🌐 Сети, VPN и приватность: протоколы обхода блокировок (VLESS, WireGuard, Shadowsocks, Xray), борьба с DPI, сетевая безопасность, прокси и маршрутизация.
4. 🛡️ Кибербезопасность: zero-day уязвимости, реальные эксплоиты, громкие взломы, утечки данных и защита инфраструктуры.
5. 🛠️ Топ инструментов и Архитектура: крутые CLI-утилиты, Open-Source находки, полезный софт для разработчиков, System Design и базы данных.

⛔ КРИТИЧЕСКОЕ ПРАВИЛО ФИЛЬТРАЦИИ:
Строго верни одно слово SKIP (и ничего больше), ТОЛЬКО если новость:
- Посвящена биологической нейрофизиологии (мозг животных, медицина, биология);
- Является абстрактной псевдонаучной философией ни о чём;
- Является прямой спам-рекламой конкретного платного курса/магазина.

Если новость интересна для кругозора будущего сеньора, сформируй карточку в формате HTML для Telegram (используй только разрешенные теги <b>, <i>, <code>, <a href="...">).
Язык: СТРОГО русский (даже если источник англоязычный).

Формат карточки:
<b>📌 [Четкий заголовок на русском: суть технологии или новости]</b>
📂 <i>{category} • Источник: {source}</i>

<b>📝 Суть в двух словах:</b>
[2-3 емких предложения: что произошло/создано, в чем инженерная или индустриальная фишка и почему это важно знать]

<b>🧠 Что изучить (разбор на пальцах):</b>
1. <b>[Термин / Концепт 1]</b> — [простое объяснение в 1 предложение на пальцах, как это работает]
2. <b>[Термин / Инструмент 2]</b> — [простое объяснение в 1 предложение]
3. <b>[Термин / Паттерн 3]</b> — [простое объяснение в 1 предложение]

💡 <b>Промпт для нейросети:</b>
<code>[Готовый вопрос для нейросети, который можно скопировать в один клик и за 5 минут детально разобраться в теме с примерами или командами]</code>

🔗 <a href="{link}">Читать первоисточник</a>

---
Новость для анализа:
Заголовок: {title}
Содержание: {summary}
"""

        for model_name in MODELS_TO_TRY:
            try:
                response = self.client.models.generate_content(
                    model=model_name,
                    contents=prompt
                )
                if response and response.text:
                    clean_text = response.text.strip()
                    if clean_text.upper().startswith("SKIP"):
                        print(f"[AIMentor] Пропущена непрактичная статья: '{title}'")
                        return None
                    return clean_text
            except Exception as e:
                print(f"[AIMentor] Модель {model_name} вернула ошибку: {e}. Пробуем следующую...")

        return None
